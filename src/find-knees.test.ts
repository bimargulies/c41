describe("findKnees", () => {
  it.each(cases)("$name", ({ histogram, options, tolerance }) => {
    const { counts, expectedLeft, expectedRight } = histogram;
    const effectiveTolerance = tolerance ?? 8; // smoothing lag budget

    const result = findKnees(counts, options);

    expect(result.leftKnee, "left knee not found").not.toBeNull();
    expect(result.rightKnee, "right knee not found").not.toBeNull();
    expect(Math.abs(result.leftKnee! - expectedLeft)).toBeLessThanOrEqual(effectiveTolerance);
    expect(Math.abs(result.rightKnee! - expectedRight)).toBeLessThanOrEqual(effectiveTolerance);
  });
});
